// container.go — Dockerfile generator for hermetic mission runs.
//
// The reproduction kit (T27-T30) bundles a docker-compose that builds
// one container per mission from a template. This file owns the
// template + a small generator function so unit tests can verify the
// resulting Dockerfile shape without invoking `docker build`.
//
// Spec: specs/truthful-completion-benchmark.md §T5.5 (item 46).
package main

import (
	"bytes"
	"fmt"
	"text/template"
)

// DockerfileSpec is the template's input. Only the fields a mission
// actually needs to vary; everything else is baked into the template.
type DockerfileSpec struct {
	// GoVersion pins the build's Go image, e.g. "1.25".
	GoVersion string
	// Mission is the mission ID being built into the image.
	Mission string
	// Agent is the agent dispatcher ID (used for labels only).
	Agent string
	// EnvAllowlist is the set of env vars permitted to pass through
	// to the runtime stage (default: only PATH + HOME). Anything not
	// listed is unset so a leaked credential can't influence the run.
	EnvAllowlist []string
}

const dockerfileTemplate = `# Generated by cmd/r1-bench/container.go — do not edit by hand.
#
# Hermetic build for mission "{{.Mission}}" run against agent "{{.Agent}}".
# - No network in the runtime stage (docker run --network=none).
# - Env-var allowlist applied at runtime entrypoint.
# - Workspace is the only mutable surface.

# syntax=docker/dockerfile:1.7

FROM golang:{{.GoVersion}}-alpine AS builder
WORKDIR /src
COPY . .
RUN go build -trimpath -o /out/r1-bench ./cmd/r1-bench

FROM alpine:3.20 AS runtime
LABEL r1.bench.mission="{{.Mission}}"
LABEL r1.bench.agent="{{.Agent}}"
RUN apk add --no-cache git bash
COPY --from=builder /out/r1-bench /usr/local/bin/r1-bench
COPY internal/bench/golden /opt/r1/golden
WORKDIR /workspace

# Default entrypoint — runs the mission. Override via docker run cmd args.
ENTRYPOINT ["/usr/local/bin/r1-bench"]
CMD ["--mission", "{{.Mission}}", "--agent", "{{.Agent}}", "--corpus", "/opt/r1/golden/truthful-completion"]
`

// GenerateDockerfile renders the template against spec and returns the
// resulting Dockerfile bytes. The renderer rejects empty Mission/Agent
// IDs so a misconfigured run can't produce a Dockerfile that builds
// successfully but executes nothing.
func GenerateDockerfile(spec DockerfileSpec) ([]byte, error) {
	if spec.Mission == "" {
		return nil, fmt.Errorf("GenerateDockerfile: Mission is empty")
	}
	if spec.Agent == "" {
		return nil, fmt.Errorf("GenerateDockerfile: Agent is empty")
	}
	if spec.GoVersion == "" {
		spec.GoVersion = "1.25"
	}
	t, err := template.New("dockerfile").Parse(dockerfileTemplate)
	if err != nil {
		return nil, fmt.Errorf("GenerateDockerfile: parse template: %w", err)
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, spec); err != nil {
		return nil, fmt.Errorf("GenerateDockerfile: execute: %w", err)
	}
	return buf.Bytes(), nil
}
